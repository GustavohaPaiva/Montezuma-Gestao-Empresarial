CREATE OR REPLACE FUNCTION public.registrar_emprestimo_pessoa(p_obra_id bigint, p_pessoa text, p_sentido text, p_valor numeric, p_descricao text DEFAULT NULL::text, p_data date DEFAULT CURRENT_DATE)
 RETURNS uuid
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
DECLARE
  v_saldo numeric;
  v_grupo uuid := gen_random_uuid();
  v_data date := COALESCE(p_data, CURRENT_DATE);
  v_pessoa text := trim(COALESCE(p_pessoa, ''));
  v_tipo text;
BEGIN
  IF p_valor IS NULL OR p_valor <= 0 THEN
    RAISE EXCEPTION 'Valor deve ser maior que zero';
  END IF;
  IF p_obra_id IS NULL THEN
    RAISE EXCEPTION 'Obra é obrigatória';
  END IF;
  IF v_pessoa = '' THEN
    RAISE EXCEPTION 'Nome da pessoa é obrigatório';
  END IF;
  IF p_sentido IS NULL OR p_sentido NOT IN ('emprestar', 'receber') THEN
    RAISE EXCEPTION 'Sentido deve ser emprestar ou receber';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM obras WHERE id = p_obra_id) THEN
    RAISE EXCEPTION 'Obra não encontrada';
  END IF;

  IF p_sentido = 'emprestar' THEN
    v_tipo := 'transferencia_saida';

    PERFORM pg_advisory_xact_lock(
      hashtextextended('obra_caixa:' || p_obra_id::text, 0)
    );

    SELECT COALESCE(SUM(
      CASE
        WHEN tipo IN ('entrada', 'transferencia_entrada') THEN valor
        WHEN tipo IN ('transferencia_saida', 'saida_pagamento') THEN -valor
        ELSE 0
      END
    ), 0)
    INTO v_saldo
    FROM obra_movimentacoes
    WHERE obra_id = p_obra_id;

    IF v_saldo < p_valor THEN
      RAISE EXCEPTION 'Saldo insuficiente na obra (disponível: %)', v_saldo;
    END IF;
  ELSE
    v_tipo := 'transferencia_entrada';
  END IF;

  INSERT INTO obra_movimentacoes (
    obra_id, tipo, valor, descricao, data,
    transferencia_grupo_id, obra_contra_id, pessoa_contra, created_by
  ) VALUES (
    p_obra_id, v_tipo, p_valor, p_descricao, v_data,
    v_grupo, NULL, v_pessoa, auth.uid()
  );

  RETURN v_grupo;
END;
$function$;

CREATE OR REPLACE FUNCTION public.registrar_saida_pagamento_lote(p_lote_id uuid)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_lote RECORD;
  v_existente uuid;
  v_id uuid;
  v_valor numeric;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Não autenticado';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM usuarios u
    WHERE u.id = auth.uid()
      AND u.tipo IN ('diretoria', 'gestor_master', 'suporte_ti', 'encarregado')
  ) THEN
    RAISE EXCEPTION 'Sem permissão para registrar saída de pagamento';
  END IF;

  SELECT id, obra_id, numero, total, status
  INTO v_lote
  FROM obra_lotes_pagamento
  WHERE id = p_lote_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Lote não encontrado';
  END IF;

  SELECT id INTO v_existente
  FROM obra_movimentacoes
  WHERE lote_pagamento_id = p_lote_id
  LIMIT 1;

  IF v_existente IS NOT NULL THEN
    RETURN v_existente;
  END IF;

  v_valor := COALESCE(v_lote.total, 0);
  IF v_valor <= 0 THEN
    RAISE EXCEPTION 'Lote sem valor para debitar do caixa';
  END IF;

  INSERT INTO obra_movimentacoes (
    obra_id, tipo, valor, descricao, data,
    lote_pagamento_id, created_by
  ) VALUES (
    v_lote.obra_id,
    'saida_pagamento',
    v_valor,
    'Pagamento extrato #' || v_lote.numero::text,
    CURRENT_DATE,
    p_lote_id,
    auth.uid()
  )
  RETURNING id INTO v_id;

  RETURN v_id;
END;
$function$;

