CREATE OR REPLACE FUNCTION private.get_obra_historico_for_cliente(p_obra_id bigint)
 RETURNS TABLE(id uuid, obra_id bigint, author_nome text, mensagem text, created_at timestamp with time zone)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'private', 'public'
AS $function$
begin
  if auth.uid() is null then
    raise exception 'Not authenticated';
  end if;

  if not exists (
    select 1
    from public.obras o
    inner join public.clientes c on c.id = o.cliente_id
    where o.id = p_obra_id
      and c.auth_user_id is not null
      and c.auth_user_id = auth.uid()
  ) then
    raise exception 'Forbidden';
  end if;

  return query
  select ch.id, ch.obra_id, ch.author_nome, ch.mensagem, ch.created_at
  from public.cliente_historico ch
  where ch.obra_id = p_obra_id
  order by ch.created_at desc;
end;
$function$;

